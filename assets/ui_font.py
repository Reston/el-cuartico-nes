def draw_ui_glyph(image, character, ink, fallback):
    rows = ROWS.get(character)
    if rows is None:
        fallback(image, 0, 0, character, ink)
        return
    rows = rows.split()
    x0 = (8 - len(rows[0])) // 2
    for y, row in enumerate(rows, 1):
        for x, value in enumerate(row, x0):
            if value == '1':
                image.putpixel((x, y), ink)
