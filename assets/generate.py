def rect(im,x,y,w,h,c):
    for yy in range(max(0,y),min(im.height,y+h)):
        for xx in range(max(0,x),min(im.width,x+w)): im.putpixel((xx,yy),c)

def text(im,x,y,s,c=3,scale=1):
    if scale==1: x=x//8*8; y=y//8*8
    for ch in s:
        for yy,row in enumerate(FONT.get(ch,['00000']*7)):
            for xx,v in enumerate(row):
                if v=='1': rect(im,x+xx*scale,y+yy*scale,scale,scale,c)
        x+=8 if scale==1 else 6*scale

def pack(im):
    out=bytearray()
    for plane in range(2):
        for y in range(8):
            out.append(sum(((im.getpixel((x,y))>>plane)&1)<<(7-x) for x in range(8)))
    return bytes(out)

